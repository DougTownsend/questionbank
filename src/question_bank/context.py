class _TextStripper(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.chunks: list[str] = []

    def handle_data(self, data: str) -> None:
        self.chunks.append(data)


_WS = re.compile(r"\s+")


def _html_to_text(html: str) -> str:
    s = _TextStripper()
    s.feed(html or "")
    return _WS.sub(" ", "".join(s.chunks)).strip()


def _correctness_label(fraction: float) -> str:
    if fraction >= 99.999:
        return "CORRECT"
    if fraction > 0:
        return f"PARTIAL ({fraction:g}%)"
    return "INCORRECT"


def _render_answers(qtype: str, answers: list[sqlite3.Row]) -> list[str]:
    lines: list[str] = []
    for a in answers:
        label = _correctness_label(a["fraction"])
        text = _html_to_text(a["text_html"])
        if qtype == "numerical" and a["tolerance"] is not None:
            text = f"{text} (±{a['tolerance']:g})"
        lines.append(f"  - [{label}] {text}")
        if a["feedback_html"]:
            fb = _html_to_text(a["feedback_html"])
            if fb:
                lines.append(f"    feedback: {fb}")
    return lines


def _render_question(q: sqlite3.Row, answers: list[sqlite3.Row]) -> str:
    parts: list[str] = []
    header = f"### [{q['id']}] {q['name'] or '(unnamed)'} — {q['moodle_type']}"
    parts.append(header)
    cat = format_category_for_display(q["raw_category"])
    if cat:
        parts.append(f"**Category:** {cat}")
    parts.append(f"**Stem:** {_html_to_text(q['stem_html'])}")
    parts.append("**Answers:**")
    parts.extend(_render_answers(q["moodle_type"], answers))
    if q["general_feedback_html"]:
        gf = _html_to_text(q["general_feedback_html"])
        if gf:
            parts.append(f"**General feedback:** {gf}")
    return "\n".join(parts)


def build_bank_context(conn: sqlite3.Connection, class_name: str) -> str:
    approved = db.list_questions(conn, status="approved")
    rejected = db.list_questions(conn, status="rejected")
    pending = db.list_questions(conn, status="pending")

    lines: list[str] = []
    lines.append(f"# Bank context — {class_name}")
    lines.append("")
    lines.append(
        f"Generated {datetime.now().isoformat(timespec='seconds')}. "
        f"Counts: {len(approved)} approved, {len(rejected)} rejected, "
        f"{len(pending)} pending."
    )
    lines.append("")
    lines.append(
        "This file is the current state of the professor's question bank for "
        "this class. Read it before generating new questions so you (a) don't "
        "duplicate anything and (b) learn from rejection notes."
    )
    lines.append("")

    lines.append(f"## Approved questions ({len(approved)})")
    lines.append("")
    if not approved:
        lines.append("_(none yet)_")
    else:
        for q in approved:
            answers = db.get_answers(conn, q["id"])
            lines.append(_render_question(q, answers))
            lines.append("")
            lines.append("---")
            lines.append("")

    lines.append(f"## Rejected questions ({len(rejected)})")
    lines.append("")
    if not rejected:
        lines.append("_(none yet)_")
    else:
        lines.append(
            "The professor rejected these. Each one has a free-text note "
            "explaining why. Do not regenerate questions with similar problems."
        )
        lines.append("")
        for q in rejected:
            answers = db.get_answers(conn, q["id"])
            note = db.latest_rejection_note(conn, q["id"]) or "(no note)"
            lines.append(
                f"### [{q['id']}] {q['name'] or '(unnamed)'} — {q['moodle_type']}"
            )
            lines.append(f"**Rejection note:** {note}")
            cat = format_category_for_display(q["raw_category"])
            if cat:
                lines.append(f"**Category:** {cat}")
            lines.append(f"**Stem:** {_html_to_text(q['stem_html'])}")
            lines.append("**Answers (as originally presented):**")
            lines.extend(_render_answers(q["moodle_type"], answers))
            lines.append("")
            lines.append("---")
            lines.append("")

    return "\n".join(lines)


def write_bank_context(class_name: str) -> Path:
    paths.ensure_class_dirs(class_name)
    conn = db.connect(paths.class_db_path(class_name))
    try:
        content = build_bank_context(conn, class_name)
    finally:
        conn.close()
    path = paths.class_dir(class_name) / BANK_CONTEXT_FILENAME
    path.write_text(content, encoding="utf-8")
    return path


def export_all(class_name: str) -> tuple[Path, Path]:
    return write_instructions(class_name), write_bank_context(class_name)
